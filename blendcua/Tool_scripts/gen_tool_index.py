#!/usr/bin/env python3
"""Generate the tool reference from the source, so it cannot go stale.

Two outputs, both derived by parsing `Tools_code/` — never hand-edited:

  Tools_ref/INDEX.md          every public function: signature + one line.
                              Read on demand; not in any prompt.
  prompt_files/current_tools.md
                              the MODULE MAP block only, rewritten in place
                              between the <!-- BEGIN/END tool-module-map -->
                              markers. The prose around it is hand-written
                              and is never touched.

The split of labour is the point: a script owns the facts that rot (what
exists, what it is called, what arguments it takes) and a human owns the
judgement that a script cannot produce (when to reach for a tool, what
trips you up). Run it after adding or renaming anything in Tools_code/:

    python Tool_scripts/gen_tool_index.py

`--check` exits 1 instead of writing if the generated text would change, and
also fails on any public function with no docstring. That is the CI hook —
it is what stops the reference drifting from the code again.
"""
from __future__ import annotations

import argparse
import ast
import sys
from pathlib import Path

HERE      = Path(__file__).resolve().parent
CODE_DIR  = HERE / "Tools_code"
REF_DIR   = HERE / "Tools_ref"
INDEX_MD  = REF_DIR / "INDEX.md"
TOOLS_MD  = HERE.parent / "prompt_files" / "current_tools.md"

BEGIN_MARK = "<!-- BEGIN tool-module-map (generated by Tool_scripts/gen_tool_index.py — do not edit by hand) -->"
END_MARK   = "<!-- END tool-module-map -->"

# Vendored third-party code is not our tool surface. `overlays/` holds the
# subprocess render helpers that perceive/handle call for you — an action file
# never imports them directly, so listing their internals would be noise.
SKIP_DIRS = ("_vendor", "__pycache__", "overlays")

# Module → the one line that tells an agent whether to open this at all. Taken
# from the module docstring when there is one; these fill the gaps. Keep them
# to "what you would be doing when you need this".
BLURB_FALLBACK = {
    "stone_texture":  "Procedural stone surface: grain, pitting and colour variation for rock and masonry.",
    "wear_textures":  "The texture map library that displace/stroke_displace pull from — noise, scratches, pitting.",
    "weathering":     "High-level weathering presets: the level an action should usually work at.",
}

# Which of the hand-written deep-dive docs covers a module, if any.
DEEP_DIVE = {
    "sculpt_native":  "Tools_ref/sculpting.md",
    "sculpt":         "Tools_ref/sculpting.md",
    "wear_textures":  "Tools_ref/wear_and_texture.md",
    "weathering":     "Tools_ref/wear_and_texture.md",
    "stone_texture":  "Tools_ref/wear_and_texture.md",
    "lib.mesh":       "Tools_ref/operations.md",
}


def modname(path: Path) -> str:
    rel = path.relative_to(CODE_DIR).with_suffix("")
    return ".".join(rel.parts)


def signature(fn: ast.FunctionDef) -> str:
    a = fn.args
    parts: list[str] = []
    defaults = [None] * (len(a.args) - len(a.defaults)) + list(a.defaults)
    for arg, dflt in zip(a.args, defaults):
        if dflt is None:
            parts.append(arg.arg)
        else:
            try:
                parts.append(f"{arg.arg}={ast.unparse(dflt)}")
            except Exception:
                parts.append(f"{arg.arg}=...")
    if a.vararg:
        parts.append("*" + a.vararg.arg)
    if a.kwonlyargs:
        if not a.vararg:
            parts.append("*")
        for arg, dflt in zip(a.kwonlyargs, a.kw_defaults):
            if dflt is None:
                parts.append(arg.arg)
            else:
                try:
                    parts.append(f"{arg.arg}={ast.unparse(dflt)}")
                except Exception:
                    parts.append(f"{arg.arg}=...")
    if a.kwarg:
        parts.append("**" + a.kwarg.arg)
    return f"{fn.name}({', '.join(parts)})"


def first_line(doc: str | None) -> str:
    """First sentence-ish of a docstring, collapsed onto one line."""
    if not doc:
        return ""
    out: list[str] = []
    for raw in doc.strip().splitlines():
        line = raw.strip()
        if not line:
            break
        out.append(line)
        if line.endswith((".", ":", "!", "?")):
            break
    text = " ".join(out)
    return text.replace("|", "\\|")


def scan() -> list[dict]:
    """One record per module, in a stable order: package dirs after top level,
    alphabetical within each. Stable order matters — the generated text has to
    be byte-identical between runs or --check is useless."""
    mods = []
    for path in sorted(CODE_DIR.rglob("*.py")):
        if any(d in path.parts for d in SKIP_DIRS):
            continue
        if path.name == "__init__.py":
            continue
        try:
            tree = ast.parse(path.read_text(encoding="utf-8"))
        except SyntaxError as exc:
            print(f"[gen] SKIP {path}: {exc}", file=sys.stderr)
            continue
        fns = [
            {
                "name": n.name,
                "sig":  signature(n),
                "doc":  first_line(ast.get_docstring(n)),
            }
            for n in tree.body
            if isinstance(n, ast.FunctionDef) and not n.name.startswith("_")
        ]
        if not fns:
            continue
        name = modname(path)
        mods.append({
            "module": name,
            "blurb":  first_line(ast.get_docstring(tree))
                      or BLURB_FALLBACK.get(name, ""),
            "fns":    fns,
        })
    mods.sort(key=lambda m: ("." in m["module"], m["module"]))
    return mods


def render_index(mods: list[dict]) -> str:
    total = sum(len(m["fns"]) for m in mods)
    out = [
        "<!-- generated by Tool_scripts/gen_tool_index.py — do not edit by hand -->",
        "",
        "# Tool index — every callable in `Tools_code/`",
        "",
        f"{total} functions across {len(mods)} modules. Signature and one line each.",
        "",
        "This is the complete list, so a tool you cannot find here does not exist.",
        "For the full explanation of any one of them:",
        "",
        "```bash",
        "python Tool_scripts/tool_help.py apply_chain",
        "```",
        "",
        "Read that before the first time you call anything. The one line below is",
        "enough to know a tool exists and roughly what it is for; it is not enough",
        "to call it correctly.",
        "",
    ]
    for m in mods:
        out.append(f"## `{m['module']}`")
        out.append("")
        if m["blurb"]:
            out.append(m["blurb"])
            out.append("")
        deep = DEEP_DIVE.get(m["module"])
        if deep:
            out.append(f"Worked examples and the traps: **`{deep}`**")
            out.append("")
        for f in m["fns"]:
            doc = f["doc"] or "_(undocumented — read the source)_"
            out.append(f"- `{f['sig']}` — {doc}")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def render_module_map(mods: list[dict]) -> str:
    """The always-in-prompt tier: one line per module, no function names. Stays
    ~50 lines however many functions land inside those modules."""
    rows = [
        BEGIN_MARK,
        "",
        "| module | what you would be doing when you need it | fns |",
        "|---|---|---|",
    ]
    for m in mods:
        blurb = m["blurb"] or "_(no module docstring)_"
        if len(blurb) > 96:
            blurb = blurb[:93].rstrip() + "…"
        rows.append(f"| `{m['module']}` | {blurb} | {len(m['fns'])} |")
    rows += ["", END_MARK]
    return "\n".join(rows)


def splice(text: str, block: str) -> str:
    i = text.find(BEGIN_MARK)
    j = text.find(END_MARK)
    if i == -1 or j == -1:
        raise SystemExit(
            f"[gen] markers not found in {TOOLS_MD}. Expected:\n"
            f"{BEGIN_MARK}\n{END_MARK}"
        )
    return text[:i] + block + text[j + len(END_MARK):]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if the generated text is out of date or any "
                         "public function lacks a docstring; write nothing")
    args = ap.parse_args()

    mods = scan()
    index_new = render_index(mods)
    tools_old = TOOLS_MD.read_text(encoding="utf-8")
    tools_new = splice(tools_old, render_module_map(mods))

    undoc = [f"{m['module']}.{f['name']}"
             for m in mods for f in m["fns"] if not f["doc"]]

    if args.check:
        stale = []
        if not INDEX_MD.exists() or INDEX_MD.read_text(encoding="utf-8") != index_new:
            stale.append(str(INDEX_MD))
        if tools_new != tools_old:
            stale.append(str(TOOLS_MD))
        for p in stale:
            print(f"[gen] OUT OF DATE: {p}", file=sys.stderr)
        for name in undoc:
            print(f"[gen] NO DOCSTRING: {name}", file=sys.stderr)
        if stale or undoc:
            print(f"\n[gen] {len(stale)} stale file(s), {len(undoc)} undocumented "
                  f"function(s). Run: python Tool_scripts/gen_tool_index.py",
                  file=sys.stderr)
            return 1
        print("[gen] up to date, every public function documented.")
        return 0

    REF_DIR.mkdir(parents=True, exist_ok=True)
    INDEX_MD.write_text(index_new, encoding="utf-8")
    TOOLS_MD.write_text(tools_new, encoding="utf-8")

    total = sum(len(m["fns"]) for m in mods)
    print(f"[gen] {INDEX_MD.relative_to(HERE.parent)}: "
          f"{total} functions, {len(mods)} modules, "
          f"{len(index_new)} chars (~{len(index_new)//4} tok)")
    print(f"[gen] {TOOLS_MD.relative_to(HERE.parent)}: module map spliced "
          f"({len(mods)} rows)")
    if undoc:
        print(f"[gen] {len(undoc)} public functions still have no docstring:")
        for name in undoc:
            print(f"        {name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
